#!/usr/bin/env bash
# Collect VM and repository facts: prints a readable report and saves the values
# to vm.env for later scripts to source.
# Expects the layout from 03-project-layout.sh: the repo is <project-dir>/main.
# Usage: 04-vm-facts.sh <project-dir> [env-file]
set -uo pipefail

project_dir="${1:?Usage: $0 <project-dir> [env-file]   (e.g. ~/<project>)}"
env_out="${2:-${AGENT_FACTORY_DIR:-$HOME/.agent-factory}/vm.env}"
project_dir="$(cd "$project_dir" 2>/dev/null && pwd)" || { echo "Error: cannot cd to $1" >&2; exit 1; }
git -C "$project_dir/main" rev-parse --git-dir >/dev/null 2>&1 \
    || { echo "Error: no repo at $project_dir/main; run 03-project-layout.sh first." >&2; exit 1; }
cd "$project_dir/main"
mkdir -p "$(dirname "$env_out")"

section() { printf '\n## %s\n' "$1"; }
run() { printf '$ %s\n' "$*"; "$@" 2>&1 || printf '(exit %s)\n' "$?"; }

{
    printf '# VM facts — %s — %s\n' "$(hostname)" "$(date -Iseconds)"
    printf 'Repository: %s\n' "$(pwd)"

    section "Build system"
    for f in CMakeLists.txt Makefile GNUmakefile configure meson.build; do
        [[ -e "$f" ]] && echo "found: $f"
    done
    echo "flex sources: $(git ls-files '*.l' | wc -l)"

    section "Git server"
    run git remote -v

    section "CPU and RAM"
    run nproc
    run free -h

    section "Disk"
    run df -h . "$HOME"
    run du -sh .
}

# Machine-readable facts for later scripts (source it). Regenerated on each run.
if [[ -e CMakeLists.txt ]]; then build_system=cmake
elif [[ -e Makefile || -e GNUmakefile ]]; then build_system=make
else build_system=unknown; fi
origin="$(git remote get-url origin 2>/dev/null)"
other_build_files="$(for f in configure meson.build; do [[ -e "$f" ]] && printf '%s ' "$f"; done)"
git_host="$(sed -E 's#^[a-z+]+://##; s#^[^@/]*@##; s#[:/].*$##' <<<"$origin")"
cat > "$env_out" <<EOF
# Generated by 04-vm-facts.sh on $(date -Iseconds); rerun to refresh.
PROJECT_REPO=$(printf '%q' "$(pwd)")
PROJECT_DIR=$(printf '%q' "$project_dir")
WORKTREES_DIR=$(printf '%q' "$project_dir/worktrees")
BUILD_SYSTEM=$build_system
OTHER_BUILD_FILES=$(printf '%q' "${other_build_files% }")
FLEX_SOURCES=$(git ls-files '*.l' | wc -l)
GIT_REMOTE_URL=$(printf '%q' "$origin")
GIT_HOST=$git_host
CPU_COUNT=$(nproc)
MEM_TOTAL_GB=$(free -g | awk '/^Mem:/ {print $2}')
DISK_FREE_GB=$(df -BG --output=avail . | tail -n 1 | tr -dc '0-9')
REPO_SIZE_MB=$(du -sm . | cut -f1)
EOF

echo
echo "Saved to $env_out"
